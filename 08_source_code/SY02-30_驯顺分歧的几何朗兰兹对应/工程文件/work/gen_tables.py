def write_tsv(name, header, rows):
    p = os.path.join(HERE, name)
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        f.write("\t".join(header) + "\n")
        for r in rows:
            assert len(r) == len(header), (name, r[0])
            f.write("\t".join(r) + "\n")
    print("wrote", p, len(rows), "rows")


